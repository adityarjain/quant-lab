@st.cache_data
def md(name: str) -> pd.DataFrame:
    """A results table written by run.py, as strings exactly as published."""
    lines = (FIG / f"{name}.md").read_text().strip().splitlines()
    cells = lambda l: [c.strip() for c in l.strip().strip("|").split("|")]
    return pd.DataFrame([cells(l) for l in lines[2:]], columns=cells(lines[0]))


def cell(name: str, col: str, **match) -> str:
    """One published number, looked up by row values (keys use underscores for spaces)."""
    df = md(name)
    for k, v in match.items():
        df = df[df[k.replace("_", " ")] == v]
    return df.iloc[0][col]


@st.cache_data
def figure_uri(name: str) -> str:
    """Light figure as an inline image (falls back to the README's dark figure if the light set is missing)."""
    import base64
    path = LIGHT / f"{name}.png"
    path = path if path.exists() else FIG / f"{name}.png"
    return "data:image/png;base64," + base64.b64encode(path.read_bytes()).decode()


def finding(fid: str, claim: str, body: str, figure: str, table: str | None = None, cols=None):
    """One result, stacked full width: claim, evidence, figure card, then the numbers in an accordion."""
    numbers = ""
    if table:
        df = md(table)
        numbers = ('<details class="ql-acc"><summary>Show the numbers</summary><div class="ql-scroll">'
                   + (df[cols] if cols else df).to_html(index=False, classes="ql-table", border=0, escape=True)
                   + "</div></details>")
    st.markdown(f"""<div class="ql-finding ql-reveal">
<p class="ql-id">{fid}</p><h3 class="ql-claim">{claim}</h3><p class="ql-body">{body}</p>
<div class="ql-figure"><img src="{figure_uri(figure)}" alt="Chart: {claim}"></div>{numbers}</div>""",
                unsafe_allow_html=True)


